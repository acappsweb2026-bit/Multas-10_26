export function getRoleLabel(role: UserRole, customRoleName?: string): string {
  if (customRoleName && customRoleName.trim().length > 0) {
    return customRoleName.trim();
  }
  switch (role) {
    case 'ADMIN':
      return 'Administrador';
    case 'GESTOR_FROTA':
      return 'Gestor de Frota';
    case 'GESTOR_RH':
      return 'Gestor de RH / Folha';
    case 'GESTOR_LOGISTICA':
      return 'Gestor de Logística';
    case 'OPERADOR':
      return 'Operador de Multas';
    case 'AUDITOR':
      return 'Auditor / Consulta';
    case 'MOTORISTA':
      return 'Motorista';
    default:
      return 'Usuário do Sistema';
  }
}

